export const COMMON_WORDS: readonly string[] = Array.from(
  new Set(
    RAW.split(/\s+/)
      .map((w) => w.trim().toUpperCase())
      .filter((w) => w.length >= 3),
  ),
)

/** Words that make satisfying, recognisable bonus challenges (4–6 letters, nouns/adjectives). */
export const BONUS_WORDS: readonly string[] = COMMON_WORDS.filter(
  (w) => w.length >= 4 && w.length <= 6,
)
